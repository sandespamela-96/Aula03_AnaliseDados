# Atividade 03 - Calculadora:

#Entrada
numero01 = float(input('Numero 1: '))
numero02 = float(input('Numero 2: '))

#Processamento
soma = numero01 + numero02
subtracao = numero01 - numero02
multiplicacao = numero01 * numero02
divisao = numero01 / numero02

#Saida
print(f'Soma: {soma}\nSubtração: {subtracao}\nMultiplicação: {multiplicacao}\nDivisão: {divisao}')